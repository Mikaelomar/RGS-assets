// quick look at signs (expansion / construction) and market furniture icons
import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1000, height: 500 } });
const logs = [];
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}\n${e.stack}`));
await page.goto('http://localhost:5173/', { waitUntil: 'load' });
await page.waitForFunction(() => window.game && document.querySelector('.title-screen'), null, { timeout: 60000 });
await page.click('text=NEW GAME'); await page.waitForTimeout(300); await page.click('input[type=checkbox]'); await page.click('text=OPEN MY SHOP'); await page.waitForTimeout(1500);
const g = (fn, arg) => page.evaluate(fn, arg);
await g(() => { const G = window.game; G.state.tutorialDone = true; G.state.money = 90000; G.sim.addXP(2500); });
await page.waitForTimeout(500);
await g(() => window.game.ui.closeAll()); await page.waitForTimeout(200); await g(() => window.game.ui.closeAll());
await g(() => { const G = window.game; G.player.pos.set(12, 0, -4); G.player.yaw = -Math.PI / 2; G.player.pitch = 0.05; });
await page.waitForTimeout(800);
await page.screenshot({ path: 'tests/out/sg_expansion.png' });
await g(() => { const G = window.game; G.state.construction = { index: 0, doneDay: 1, doneMin: 700 }; G.rebuildStore();
  const sg = G.building.signs.find((s) => s.kind === 'expansion'); const p = sg.mesh.position; const n = new p.constructor(0, 0, 1).applyQuaternion(sg.mesh.quaternion);
  G.player.pos.set(p.x + n.x * 4, 0, p.z + n.z * 4); G.player.yaw = Math.atan2(n.x, n.z); G.player.pitch = 0.12; });
await page.waitForTimeout(800);
await page.screenshot({ path: 'tests/out/sg_construction.png' });
await g(() => { window.game.state.construction = null; window.game.rebuildStore(); window.game.app.open('market'); });
await page.waitForTimeout(500);
await page.click('.subtab:text-is("FURNITURE")');
await page.waitForTimeout(400);
await page.evaluate(() => { const el = [...document.querySelectorAll('.wbody *')].find((e) => e.scrollHeight > e.clientHeight + 50); if (el) el.scrollTop = 99999; });
await page.waitForTimeout(400);
await page.screenshot({ path: 'tests/out/sg_market_furn.png' });
console.log(logs.join('\n') || 'no errors');
await browser.close();
